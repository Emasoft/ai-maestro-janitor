"""AppArmor / SELinux profile-gap security patterns.

Wave-33 distillation round 19, angle: AppArmor / SELinux Profile Gaps.

Catalogue of 9 LSM-profile-gap patterns distilled in
`reports/distill-round-19/selinux-apparmor-profile-gaps.md`. Targets
host-level SELinux config, setsebool postinst scripts, audit2allow .te
files, AppArmor mode-switch CLI calls, systemd units, Docker security-opt
custom types, libapparmor C API calls, Kubernetes securityContext absence,
and Dockerfile RUN layers.

What is NOT here (already shipped — DO NOT duplicate):

  * Container runtime `--security-opt apparmor=unconfined` / `seccomp=unconfined` /
    `label=disable` — `container_runtime_patterns.py` rule `cre-runtime-lsm-unconfined`.
  * Docker Compose `security_opt: [apparmor:unconfined, label:disable]` —
    `sandbox_escape_patterns.py` rule `container-compose-seccomp-unconfined`.
  * K8s `appArmorProfile.type: Unconfined` / `seccompProfile.type: Unconfined`
    (structured 1.30+ API) — `sandbox_escape_patterns.py` rule `k8s-securitycontext-gap`.
  * `docker run --privileged` — `container_runtime_patterns.py` `cre-runtime-privileged-flag`.
  * polkit `.rules` permissive — `linux_privesc_patterns.py`.

What IS here (9 net-new rules, regex-only, all RE2-safe):

  * sa-selinux-host-config-permissive              (CRITICAL)
  * sa-setsebool-persistent-high-risk              (HIGH)
  * sa-audit2allow-wildcard-allow                  (HIGH)
  * sa-apparmor-complain-mode-in-script            (HIGH)
  * sa-systemd-apparmor-profile-name               (MEDIUM)
  * sa-docker-selinux-custom-permissive-type       (MEDIUM)
  * sa-libapparmor-change-to-unconfined            (CRITICAL)
  * sa-k8s-securitycontext-no-lsm-profile          (MEDIUM)
  * sa-dockerfile-runcmd-aa-complain               (HIGH)

Public surface:

  * Rule(id, name, severity, description, pattern, owasp_asi)
  * RULES — ordered tuple of every rule.
  * scan_text(text) -> list[Finding]
  * Finding(rule_id, line, column, matched_text, severity, description,
            owasp_asi)

OWASP ASI mapping used:
  ASI-02 — Secret / capability leak (libapparmor unconfined API call)
  ASI-05 — Security Misconfiguration (all LSM profile gaps)

All regexes are RE2-compatible (no backreferences, no lookbehind, no
catastrophic backtracking shapes). Patterns are PRE-COMPILED at module
load. Fail-fast: callers receive structured Finding tuples, never raised
exceptions on benign input.
"""

from __future__ import annotations

import re
from typing import NamedTuple

# ---- Data model ---------------------------------------------------------


class Finding(NamedTuple):
    """A single rule match."""

    rule_id: str
    line: int
    column: int
    matched_text: str
    severity: str
    description: str
    owasp_asi: str


class Rule(NamedTuple):
    """A compiled detection rule."""

    id: str
    name: str
    severity: str
    description: str
    pattern: re.Pattern  # type: ignore[type-arg]
    owasp_asi: str


# ---- Pre-compiled patterns -----------------------------------------------

# SAG-01: /etc/selinux/config or Ansible selinux module with permissive/disabled
# Three shapes: (a) bare config key, (b) Ansible state: value, (c) sed/echo rewrite
_SAG01 = re.compile(
    r"(?:^SELINUX=(?:permissive|disabled)\s*$"
    r"|\bstate:\s*(?:permissive|disabled)\b"
    r"|(?:sed\s[^;|&\n]{0,100}|echo\s[^;|&\n]{0,100})SELINUX=(?:permissive|disabled)\b)",
    re.MULTILINE,
)

# SAG-02: setsebool -P with a dangerous boolean set to on/1/true
_SAG02 = re.compile(
    r"\bsetsebool\s+-P\s+"
    r"(?:allow_exec(?:heap|mem|stack)|httpd_exec(?:mem|cgi)|"
    r"ssh_sysadm_login|container_manage_cgroup|allow_domain_fd_use)"
    r"\s+(?:1|on|true)\b",
    re.MULTILINE,
)

# SAG-03: audit2allow wildcard allow rule in .te policy files
# Two shapes: (a) wildcard { * } permission set, (b) broad resource type + dangerous perms
_SAG03 = re.compile(
    r"(?:^\s*allow\s+\S+\s+\S+:\S+\s+\{\s*\*\s*\}"
    r"|^\s*allow\s+\S+\s+(?:file_type|fs_type|domain|unlabeled_t)\s*:\s*"
    r"(?:file|process|dir)\s+\{[^}]{0,200}(?:execute|write)\b"
    r"|#\s*Generated by audit2allow\b)",
    re.MULTILINE,
)

# SAG-04: aa-complain mode-switch in shell/Ansible (not Dockerfile-specific RUN)
# Two shapes: (a) shell aa-complain <arg>, (b) Ansible state: complain
_SAG04 = re.compile(
    r"(?:\baa-complain\s+\S+"
    r"|\bstate:\s*complain\b)",
    re.MULTILINE,
)

# SAG-05: AppArmorProfile= directive in systemd unit
_SAG05 = re.compile(
    r"^\s*AppArmorProfile\s*=\s*.+",
    re.MULTILINE,
)

# SAG-06: Docker --security-opt label:type= with permissive type, or K8s legacy annotation
_SAG06 = re.compile(
    r"(?:--security-opt\s+label:type=(?:unconfined_t|spc_t|svirt_t|initrc_t)\b"
    r"|container\.apparmor\.security\.beta\.kubernetes\.io/[^:]+:\s*unconfined\b)",
    re.MULTILINE,
)

# SAG-07: libapparmor C API call with "unconfined" as target hat/profile
_SAG07 = re.compile(
    r'\baa_change_(?:hat|onexec|profile)\s*\([^)]{0,200}"unconfined"',
    re.MULTILINE,
)

# SAG-08: K8s securityContext with hardening fields but no seccompProfile/appArmorProfile
# Two-pass: anchor detects a securityContext block containing hardening fields;
# the window check (absence) is done in scan_text logic below.
_SAG08_ANCHOR = re.compile(
    r"\bsecurityContext:\s*\n(?:[ \t]+\S[^\n]*\n){0,40}"
    r"[ \t]+(?:allowPrivilegeEscalation|runAsNonRoot|readOnlyRootFilesystem)\b",
    re.MULTILINE,
)
_SAG08_LSM_PRESENT = re.compile(
    r"\b(?:seccompProfile|appArmorProfile)\b",
)

# SAG-09: Dockerfile RUN layer calling aa-complain, or entrypoint path-anchored aa-complain
_SAG09 = re.compile(
    r"(?:^\s*RUN\s+[^\n]{0,200}\baa-complain\b"
    r"|\baa-complain\s+/etc/apparmor\.d/\S+)",
    re.MULTILINE,
)


# ---- Helper --------------------------------------------------------------


def _line_col(text: str, pos: int) -> tuple[int, int]:
    """Return (1-based line, 1-based column) for a byte offset in *text*."""
    line = text.count("\n", 0, pos) + 1
    last_nl = text.rfind("\n", 0, pos)
    col = pos - last_nl  # last_nl is -1 when pos is on line 1 → col = pos + 1
    return line, col


