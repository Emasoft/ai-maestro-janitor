# ---- Scanner -------------------------------------------------------------


def scan_text(text: str) -> list[Finding]:
    """Scan *text* for all LSM profile-gap patterns and return sorted findings.

    Findings are deduplicated by (rule_id, line, column) and sorted by
    (line, column, rule_id). The two-pass SAG-08 rule emits a finding only
    when the matched securityContext window does NOT contain seccompProfile
    or appArmorProfile.
    """
    seen: set[tuple[str, int, int]] = set()
    findings: list[Finding] = []

    for rule in RULES:
        if rule.id == "sa-k8s-securitycontext-no-lsm-profile":
            # Two-pass: anchor match + absence of LSM fields in a 40-line window
            # starting from the securityContext: line.  The anchor regex ends at the
            # first hardening field, but seccompProfile/appArmorProfile may appear
            # AFTER that field in the same block — so we extend the window to 40
            # lines from the anchor start.
            for m in rule.pattern.finditer(text):
                # Collect up to 40 lines from the start of the match
                block_start = m.start()
                # Walk forward up to 40 newlines from the start
                pos = block_start
                for _ in range(40):
                    idx = text.find("\n", pos)
                    if idx == -1:
                        pos = len(text)
                        break
                    pos = idx + 1
                window = text[block_start:pos]
                if _SAG08_LSM_PRESENT.search(window):
                    continue  # LSM profile present — not a gap
                line, col = _line_col(text, m.start())
                key = (rule.id, line, col)
                if key in seen:
                    continue
                seen.add(key)
                findings.append(
                    Finding(
                        rule_id=rule.id,
                        line=line,
                        column=col,
                        matched_text=m.group(0)[:120],
                        severity=rule.severity,
                        description=rule.description,
                        owasp_asi=rule.owasp_asi,
                    )
                )
        else:
            for m in rule.pattern.finditer(text):
                line, col = _line_col(text, m.start())
                key = (rule.id, line, col)
                if key in seen:
                    continue
                seen.add(key)
                findings.append(
                    Finding(
                        rule_id=rule.id,
                        line=line,
                        column=col,
                        matched_text=m.group(0)[:120],
                        severity=rule.severity,
                        description=rule.description,
                        owasp_asi=rule.owasp_asi,
                    )
                )

    findings.sort(key=lambda f: (f.line, f.column, f.rule_id))
    return findings
